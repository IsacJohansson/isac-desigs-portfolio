export class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('ij_portfolio_lang') || 'en';
  }

  init() {
    this.setLanguage(this.currentLang);
    this.bindEvents();
  }

  bindEvents() {
    document.querySelectorAll('[data-lang-toggle]').forEach(btn => {
      btn.addEventListener('click', (e) => {
        const lang = e.currentTarget.getAttribute('data-lang-toggle');
        if (lang && translations[lang]) {
          this.setLanguage(lang);
        }
      });
    });
  }

  setLanguage(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('ij_portfolio_lang', lang);
    document.documentElement.lang = lang;

    // Update active button UI
    document.querySelectorAll('[data-lang-toggle]').forEach(btn => {
      const isCurrent = btn.getAttribute('data-lang-toggle') === lang;
      if (isCurrent) {
        btn.classList.add('bg-blue-600', 'text-white', 'border-blue-500', 'font-bold');
        btn.classList.remove('text-slate-400', 'hover:text-white', 'border-slate-800');
      } else {
        btn.classList.remove('bg-blue-600', 'text-white', 'border-blue-500', 'font-bold');
        btn.classList.add('text-slate-400', 'hover:text-white', 'border-slate-800');
      }
    });

    // Translate all elements with data-i18n attribute
    const dict = translations[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = dict[key];
        } else {
          el.innerHTML = dict[key];
        }
      }
    });

    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }
}
